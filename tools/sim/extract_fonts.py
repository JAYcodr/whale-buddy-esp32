#!/usr/bin/env python3
"""Extract selected U8g2 C font arrays for the Mac host simulator."""

import os
import re
import sys

FONTS = [
    "u8g2_font_wqy14_t_gb2312",
    "u8g2_font_wqy16_t_gb2312",
    "u8g2_font_helvB14_tf",
    "u8g2_font_helvB18_tf",
    "u8g2_font_logisoso24_tf",
]


def main() -> int:
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
    src = os.path.join(
        root,
        ".pio/libdeps/waveshare-esp32s3-touch-amoled-1-8/U8g2/src/clib/u8g2_fonts.c",
    )
    dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        root, "tools/sim/build/sim_u8g2_fonts.c"
    )
    with open(src, "r", encoding="latin-1") as f:
        text = f.read()

    out = [
        "/* Auto-generated by tools/sim/extract_fonts.py */",
        "#include <stdint.h>",
        "#define U8G2_FONT_SECTION(name)",
        "",
    ]
    for name in FONTS:
        m = re.search(rf"const uint8_t {name}\[\d+\].*?;\s*\n", text, re.S)
        if not m:
            raise RuntimeError(f"Font symbol not found in u8g2_fonts.c: {name}")
        out.append(m.group(0))

    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
