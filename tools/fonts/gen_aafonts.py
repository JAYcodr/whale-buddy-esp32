#!/usr/bin/env python3
"""Generate LVGL-style 4-bpp anti-aliased fonts (PingFang SC + DIN Alternate Bold)."""

import os
from PIL import Image, ImageDraw, ImageFont

PINGFANG_PATH = (
    "/System/Library/AssetsV2/com_apple_MobileAsset_Font8/"
    "86ba2c91f017a3749571a82f2c6d890ac7ffb2fb.asset/AssetData/PingFang.ttc"
)
DIN_PATH = "/System/Library/Fonts/Supplemental/DIN Alternate Bold.ttf"
PINGFANG_INDEX = 7  # PingFang SC Medium

PUNCT_AND_EXTRA = (
    "，。、：；！？（）【】《》“”‘’「」—…·￥°×÷＋－／｜→"
    "浏渲诺瓦啰哒嘛呗呢嗯噢哈喽喔咔喵炫盹憩唔嗨咦咧嘟啾噗"
)


def build_cjk_charset() -> list[int]:
    cps = set(range(0x20, 0x7F))
    for b1 in range(0xB0, 0xD8):
        for b2 in range(0xA1, 0xFF):
            try:
                ch = bytes([b1, b2]).decode("gb2312")
                if len(ch) == 1 and ord(ch) <= 0xFFFF:
                    cps.add(ord(ch))
            except UnicodeDecodeError:
                pass
    for ch in PUNCT_AND_EXTRA:
        if ord(ch) <= 0xFFFF:
            cps.add(ord(ch))
    return sorted(cps)


def build_ascii_charset() -> list[int]:
    cps = set(range(0x20, 0x7F))
    for ch in "·°¥￥×÷—":
        cps.add(ord(ch))
    return sorted(cps)


def render_font(name: str, font_path: str, index: int, size: int, cps: list[int],
                gamma: float, fallback_var: str) -> tuple[str, int]:
    font = ImageFont.truetype(font_path, size, index=index)
    ascent, descent = font.getmetrics()
    line_h = ascent + descent

    glyph_rows = []
    bitmap_bytes = bytearray()

    for cp in cps:
        ch = chr(cp)
        bbox = font.getbbox(ch, anchor="ls")
        adv = int(round(font.getlength(ch)))
        if bbox is None or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
            glyph_rows.append((cp, 0, 0, len(bitmap_bytes), max(1, adv), 0, 0))
            continue

        x0, y0, x1, y1 = bbox
        w = x1 - x0
        h = y1 - y0
        if w > 255 or h > 255 or adv > 255:
            continue

        img = Image.new("L", (w, h), 0)
        draw = ImageDraw.Draw(img)
        draw.text((-x0, -y0), ch, fill=255, font=font, anchor="ls")
        px = img.tobytes()

        # Gamma lift slightly preserves thin horizontal CJK strokes on black OLED.
        nibbles = []
        for a in px:
            if a == 0:
                q = 0
            else:
                v = (a / 255.0) ** gamma
                q = min(15, max(1, int(round(v * 15.0))))
            nibbles.append(q)

        data_off = len(bitmap_bytes)
        for i in range(0, len(nibbles), 2):
            hi = nibbles[i]
            lo = nibbles[i + 1] if i + 1 < len(nibbles) else 0
            bitmap_bytes.append((hi << 4) | lo)

        glyph_rows.append((cp, w, h, data_off, max(0, min(255, adv)), max(-128, min(127, x0)), max(-128, min(127, y0))))

    glyph_rows.sort(key=lambda r: r[0])

    lines = [
        f"static const AaGlyph kGlyphs_{name}[] = {{",
    ]
    for cp, w, h, off, xadv, xoff, yoff in glyph_rows:
        lines.append(f"  {{0x{cp:04X}u, {w}u, {h}u, {off}u, {xadv}u, {xoff}, {yoff}}},")
    lines.append("};")
    lines.append(f"static const uint8_t kData_{name}[] = {{")
    for i in range(0, len(bitmap_bytes), 20):
        chunk = ",".join(f"0x{b:02X}" for b in bitmap_bytes[i:i + 20])
        lines.append(f"  {chunk},")
    lines.append("};")
    lines.append(
        f"const AaFont {name} = {{ {line_h}u, {ascent}u, {descent}u, "
        f"{len(glyph_rows)}u, kGlyphs_{name}, kData_{name}, {fallback_var} }};"
    )
    total_bytes = len(glyph_rows) * 12 + len(bitmap_bytes)
    print(f"{name}: {len(glyph_rows)} glyphs, bitmap={len(bitmap_bytes)} B, total~{total_bytes // 1024} KB")
    return "\n".join(lines), total_bytes


def main() -> int:
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
    out_cpp = os.path.join(root, "src/ui/aafont_data.cpp")

    cjk_cps = build_cjk_charset()
    asc_cps = build_ascii_charset()

    specs = [
        ("g_fontPf16",  PINGFANG_PATH, PINGFANG_INDEX, 16, cjk_cps, 0.84, "nullptr"),
        ("g_fontPf20",  PINGFANG_PATH, PINGFANG_INDEX, 20, cjk_cps, 0.85, "nullptr"),
        ("g_fontDin17", DIN_PATH,      0,              17, asc_cps, 0.88, "&g_fontPf16"),
        ("g_fontDin22", DIN_PATH,      0,              22, asc_cps, 0.88, "&g_fontPf20"),
        ("g_fontDin30", DIN_PATH,      0,              30, asc_cps, 0.90, "&g_fontPf20"),
    ]

    blocks = [
        "/* Auto-generated by tools/fonts/gen_aafonts.py — do not edit manually */",
        '#include "ui/aafont.h"',
        "",
        "extern const AaFont g_fontPf16;",
        "extern const AaFont g_fontPf20;",
        "extern const AaFont g_fontDin17;",
        "extern const AaFont g_fontDin22;",
        "extern const AaFont g_fontDin30;",
        "",
    ]
    grand_total = 0
    for spec in specs:
        txt, sz = render_font(*spec)
        blocks.append(txt)
        blocks.append("")
        grand_total += sz

    with open(out_cpp, "w", encoding="utf-8") as f:
        f.write("\n".join(blocks))
    print(f"Wrote {out_cpp} (approx total {grand_total / 1024:.1f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
